  <script>

    // ========================================
// FAQ PAGE FUNCTIONALITY
// ========================================

document.addEventListener('DOMContentLoaded', function() {

    // ========================================
    // FAQ SEARCH
    // ========================================
    
    const faqSearch = document.getElementById('faqSearch');
    const faqItems = document.querySelectorAll('.faq-item');
    const faqQuestions = document.querySelectorAll('.faq-question h4');
    const faqAnswers = document.querySelectorAll('.faq-answer p');

    if (faqSearch) {
        faqSearch.addEventListener('input', function() {
            const searchTerm = this.value.toLowerCase().trim();
            
            faqItems.forEach((item, index) => {
                const questionText = faqQuestions[index]?.textContent.toLowerCase() || '';
                const answerText = faqAnswers[index]?.textContent.toLowerCase() || '';
                
                if (questionText.includes(searchTerm) || answerText.includes(searchTerm)) {
                    item.style.display = 'block';
                    // Highlight matching text
                    if (searchTerm.length > 0) {
                        item.style.borderColor = '#d6b37a';
                        item.style.boxShadow = '0 5px 30px rgba(214, 179, 122, 0.15)';
                    } else {
                        item.style.borderColor = '';
                        item.style.boxShadow = '';
                    }
                } else {
                    item.style.display = 'none';
                }
            });
        });

        // Search button click
        const searchBtn = document.querySelector('.faq-search-btn');
        if (searchBtn) {
            searchBtn.addEventListener('click', function(e) {
                e.preventDefault();
                faqSearch.dispatchEvent(new Event('input'));
            });
        }

        // Enter key
        faqSearch.addEventListener('keypress', function(e) {
            if (e.key === 'Enter') {
                e.preventDefault();
                faqSearch.dispatchEvent(new Event('input'));
            }
        });
    }

    // ========================================
    // FAQ ACCORDION - Multiple items can be open
    // ========================================
    
    const faqQuestionsAll = document.querySelectorAll('.faq-question');
    
    faqQuestionsAll.forEach((question, index) => {
        question.addEventListener('click', function() {
            const target = this.getAttribute('data-bs-target');
            const targetElement = document.querySelector(target);
            const parentAccordion = this.closest('.faq-accordion');
            
            // Check if target is already open
            const isOpen = targetElement.classList.contains('show');
            
            // Close all items in this accordion if you want single open
            // Uncomment below for single open
            /*
            const allItems = parentAccordion.querySelectorAll('.faq-item');
            allItems.forEach(item => {
                item.classList.remove('active');
                const collapse = item.querySelector('.collapse');
                if (collapse) {
                    collapse.classList.remove('show');
                }
            });
            */
            
            // Toggle current
            if (isOpen) {
                this.closest('.faq-item').classList.remove('active');
            } else {
                this.closest('.faq-item').classList.add('active');
            }
        });
    });

    // ========================================
    // FAQ TABS - Smooth tab switching
    // ========================================
    
    const tabLinks = document.querySelectorAll('.faq-tabs .nav-link');
    
    tabLinks.forEach(tab => {
        tab.addEventListener('click', function() {
            // Remove active from all tabs
            tabLinks.forEach(t => t.classList.remove('active'));
            this.classList.add('active');
            
            // Hide all tab panes
            const tabPanes = document.querySelectorAll('.tab-pane');
            tabPanes.forEach(pane => {
                pane.classList.remove('show', 'active');
            });
            
            // Show target pane
            const target = this.getAttribute('data-bs-target');
            const targetPane = document.querySelector(target);
            if (targetPane) {
                targetPane.classList.add('show', 'active');
                
                // Reset search
                if (faqSearch) {
                    faqSearch.value = '';
                    faqSearch.dispatchEvent(new Event('input'));
                }
            }
        });
    });

    // ========================================
    // SCROLL TO FAQ SECTION
    // ========================================
    
    // If URL has hash, scroll to that FAQ
    if (window.location.hash) {
        const targetId = window.location.hash;
        const targetElement = document.querySelector(targetId);
        if (targetElement) {
            setTimeout(() => {
                targetElement.scrollIntoView({ behavior: 'smooth', block: 'center' });
                // Open the FAQ
                const parentItem = targetElement.closest('.faq-item');
                if (parentItem) {
                    const collapse = parentItem.querySelector('.collapse');
                    if (collapse && !collapse.classList.contains('show')) {
                        parentItem.classList.add('active');
                        collapse.classList.add('show');
                    }
                }
            }, 500);
        }
    }

});

